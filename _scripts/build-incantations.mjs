async function writeIfChanged(path, contents) {
  let current = "";
  try {
    current = await readFile(path, "utf8");
  } catch {
    // The file does not exist yet.
  }
  if (current !== contents) {
    await writeFile(path, contents);
  }
}

async function removeGeneratedPage(path) {
  try {
    const contents = await readFile(path, "utf8");
    if (!contents.includes(generatedPageMarker)) {
      throw new Error("Refusing to remove incantations.html because it was not generated by this script.");
    }
    await rm(path);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
}

async function updatePersonStructuredData(source, config, visible) {
  const pattern =
    /<script type="application\/ld\+json" id="person-jsonld">\s*([\s\S]*?)\s*<\/script>/;
  const match = source.match(pattern);
  if (!match) throw new Error("Could not find Person structured data.");
  const person = JSON.parse(match[1]);
  if (visible) {
    person.award = config.award;
  } else {
    delete person.award;
  }
  const replacement = `<script type="application/ld+json" id="person-jsonld">\n${JSON.stringify(person, null, 2)}\n</script>`;
  return source.replace(pattern, replacement);
}

async function copyProductionSnapshot(visible) {
  const output = join(root, "_site");
  const publicPaths = [
    "404.html",
    "CNAME",
    "apple-touch-icon.png",
    "author-photo.jpg",
    "favicon-32.png",
    "favicon.ico",
    "index.html",
    "og-image.jpg",
    "publications.html",
    "publications.js",
    "styles.css",
    "submittable-filter",
  ];
  if (visible) publicPaths.push("incantations.html");

  await rm(output, { recursive: true, force: true });
  await mkdir(output, { recursive: true });
  for (const relativePath of publicPaths) {
    const source = join(root, relativePath);
    await access(source);
    const sourceStat = await stat(source);
    await cp(source, join(output, relativePath), {
      recursive: sourceStat.isDirectory(),
    });
  }
}

const configArgument = argumentValue("config");
const configPath = configArgument
  ? isAbsolute(configArgument)
    ? configArgument
    : resolve(process.cwd(), configArgument)
  : defaultConfigPath;
const config = JSON.parse(await readFile(configPath, "utf8"));
validateConfig(config);

const requestedStatus = argumentValue("status");
if (requestedStatus) {
  if (!allowedStatuses.has(requestedStatus)) {
    throw new Error("--status must be hidden, announced, or published.");
  }
  config.status = requestedStatus;
}

const visible = config.status !== "hidden";
const navItem = visible
  ? '    <li><a href="incantations.html">Incantations</a></li>'
  : "";

let indexHtml = await readFile(join(root, "index.html"), "utf8");
indexHtml = replaceHtmlRegion(indexHtml, "INCANTATIONS_NAV", navItem);
indexHtml = replaceHtmlRegion(
  indexHtml,
  "INCANTATIONS_FEATURE",
  visible ? homepageFeature(config) : "",
);
indexHtml = await updatePersonStructuredData(indexHtml, config, visible);
await writeIfChanged(join(root, "index.html"), indexHtml);

let publicationsHtml = await readFile(join(root, "publications.html"), "utf8");
publicationsHtml = replaceHtmlRegion(publicationsHtml, "INCANTATIONS_NAV", navItem);
publicationsHtml = replaceHtmlRegion(
  publicationsHtml,
  "INCANTATIONS_AWARDS",
  visible ? awardsSection(config) : "",
);
await writeIfChanged(join(root, "publications.html"), publicationsHtml);

let publicationsJs = await readFile(join(root, "publications.js"), "utf8");
publicationsJs = replaceJsRegion(
  publicationsJs,
  "INCANTATIONS_PUBLICATION",
  visible ? incantationsPublication(config) : "",
);
await writeIfChanged(join(root, "publications.js"), publicationsJs);

const incantationsPath = join(root, "incantations.html");
if (visible) {
  await writeIfChanged(incantationsPath, dedicatedPage(config));
} else {
  await removeGeneratedPage(incantationsPath);
}

await copyProductionSnapshot(visible);
console.log(`Built the ${config.status} state in ${join(root, "_site")}.`);

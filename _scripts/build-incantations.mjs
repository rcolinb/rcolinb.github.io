const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const defaultConfigPath = join(root, "_incantations.json");
const allowedStatuses = new Set(["hidden", "announced", "published"]);
const generatedPageMarker = "<!-- Generated by _scripts/build-incantations.mjs. -->";

function argumentValue(name) {
  const prefix = `--${name}=`;
  const argument = process.argv.slice(2).find((value) => value.startsWith(prefix));
  return argument ? argument.slice(prefix.length) : "";
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function renderParagraphs(value, className = "") {
  const classAttribute = className ? ` class="${className}"` : "";
  return String(value)
    .trim()
    .split(/\n\s*\n/)
    .filter(Boolean)
    .map((paragraph) => `<p${classAttribute}>${escapeHtml(paragraph)}</p>`)
    .join("\n");
}

function validateUrl(value, field) {
  if (!value) return;
  let parsed;
  try {
    parsed = new URL(value);
  } catch {
    throw new Error(`${field} must be empty or a complete URL.`);
  }
  if (!["http:", "https:"].includes(parsed.protocol)) {
    throw new Error(`${field} must use http or https.`);
  }
}

function validateConfig(config) {
  const requiredFields = [
    "status",
    "title",
    "award",
    "judge",
    "issue",
    "description",
  ];
  const optionalFields = [
    "announcementUrl",
    "publicationUrl",
    "purchaseUrl",
    "citation",
    "excerpt",
    "judgeQuote",
    "authorNote",
  ];

  requiredFields.forEach((field) => {
    if (typeof config[field] !== "string" || !config[field].trim()) {
      throw new Error(`${field} must be a non-empty string.`);
    }
  });
  optionalFields.forEach((field) => {
    if (typeof config[field] !== "string") {
      throw new Error(`${field} must be a string.`);
    }
  });
  if (!allowedStatuses.has(config.status)) {
    throw new Error("status must be hidden, announced, or published.");
  }
  ["announcementUrl", "publicationUrl", "purchaseUrl"].forEach((field) => {
    validateUrl(config[field], field);
  });
}

function replaceHtmlRegion(source, name, content) {
  const start = `<!-- ${name}:START -->`;
  const end = `<!-- ${name}:END -->`;
  const markerIndex = source.indexOf(start);
  if (markerIndex === -1) {
    throw new Error(`Missing generated region ${name}.`);
  }
  const lineStart = source.lastIndexOf("\n", markerIndex) + 1;
  const indent = source.slice(lineStart, markerIndex);
  const pattern = new RegExp(
    `${start.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${end.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`,
  );
  return source.replace(
    pattern,
    `${start}${content ? `\n${content}\n` : "\n"}${indent}${end}`,
  );
}

function replaceJsRegion(source, name, content) {
  const start = `// ${name}:START`;
  const end = `// ${name}:END`;
  const pattern = new RegExp(
    `${start.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${end.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`,
  );
  if (!pattern.test(source)) {
    throw new Error(`Missing generated region ${name}.`);
  }
  return source.replace(pattern, `${start}${content ? `\n${content}\n  ` : "\n  "}${end}`);
}

function externalAction(url, label) {
  if (!url) return "";
  return `<a class="essay-action" href="${escapeHtml(url)}" target="_blank" rel="noopener">${escapeHtml(label)}</a>`;
}

function primaryAction(config) {
  if (config.status === "announced") {
    return externalAction(config.announcementUrl, "View the announcement");
  }
  if (config.status === "published" && config.publicationUrl) {
    return externalAction(config.publicationUrl, "Read the essay");
  }
  if (config.status === "published" && config.purchaseUrl) {
    return externalAction(config.purchaseUrl, "Get the issue");
  }
  return "";
}

function homepageFeature(config) {
  const action = primaryAction(config);
  const actionMarkup = action
    ? `      <div class="essay-actions">${action}</div>\n`
    : "";
  const supportingText =
    config.status === "announced"
      ? `Selected by ${config.judge}. Forthcoming in the ${config.issue} issue of Indiana Review.`
      : `Selected by ${config.judge}. Published in the ${config.issue} issue of Indiana Review.`;

  return `<section id="incantations-feature" class="essay-feature-section">
  <div class="section-content">
    <article class="essay-feature reveal">
      <p class="essay-kicker">${escapeHtml(config.award)}</p>
      <h2 class="essay-feature-title"><a href="incantations.html">&ldquo;${escapeHtml(config.title)}&rdquo;</a></h2>
      <p class="essay-feature-text">${escapeHtml(supportingText)}</p>
${actionMarkup}    </article>
  </div>
</section>`;
}

function awardsSection(config) {
  const awardName = config.award.replace(/^Winner of the\s+/i, "");
  return `<section class="recognition-section reveal" aria-labelledby="awards-heading">
      <h2 class="work-category-title" id="awards-heading">Awards &amp; Recognition</h2>
      <div class="award-entry">
        <p class="award-title">${escapeHtml(awardName)}</p>
        <p class="award-work"><a href="incantations.html">&ldquo;${escapeHtml(config.title)}&rdquo;</a>, selected by ${escapeHtml(config.judge)}</p>
      </div>
    </section>`;
}

function incantationsPublication(config) {
  const publication = {
    genre: "cnf",
    status: config.status === "announced" ? "forthcoming" : "published",
    title: escapeHtml(config.title),
  };

  if (config.status === "announced") {
    publication.citation = `Indiana Review. Forthcoming, ${escapeHtml(config.issue)}.`;
  } else if (config.citation) {
    publication.citation = escapeHtml(config.citation);
  } else {
    publication.citation = `Indiana Review. ${escapeHtml(config.issue)}.`;
  }

  if (config.status === "published" && config.publicationUrl) {
    publication.url = config.publicationUrl;
    publication.linkText = "Read &rarr;";
  } else if (config.status === "published" && config.purchaseUrl) {
    publication.url = config.purchaseUrl;
    publication.linkText = "Get the issue &rarr;";
  }

  return `  ${JSON.stringify(publication)},`;
}

function publicationDetailSections(config) {
  if (config.status !== "published") return "";
  const sections = [];

  if (config.citation) {
    sections.push(`<section class="essay-detail reveal" aria-labelledby="citation-heading">
        <h2 id="citation-heading">Publication</h2>
        <p class="essay-citation">&ldquo;${escapeHtml(config.title)}.&rdquo; ${escapeHtml(config.citation)}</p>
      </section>`);
  }
  if (config.judgeQuote) {
    sections.push(`<section class="essay-detail reveal" aria-labelledby="judge-quote-heading">
        <h2 id="judge-quote-heading">From the Judge</h2>
        <blockquote class="judge-quote">
          ${renderParagraphs(config.judgeQuote)}
          <cite>${escapeHtml(config.judge)}</cite>
        </blockquote>
      </section>`);
  }
  if (config.excerpt) {
    sections.push(`<section class="essay-detail reveal" aria-labelledby="excerpt-heading">
        <h2 id="excerpt-heading">Excerpt</h2>
        <div class="essay-prose">
          ${renderParagraphs(config.excerpt)}
        </div>
      </section>`);
  }
  if (config.authorNote) {
    sections.push(`<section class="essay-detail reveal" aria-labelledby="author-note-heading">
        <h2 id="author-note-heading">Author&#39;s Note</h2>
        <div class="essay-prose">
          ${renderParagraphs(config.authorNote)}
        </div>
      </section>`);
  }

  return sections.join("\n\n      ");
}


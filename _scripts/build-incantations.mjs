async function writeIfChanged(path, contents) {
  let current = "";
  try {
    current = await readFile(path, "utf8");
  } catch {
    // The file does not exist yet.
  }
  if (current !== contents) {
    await writeFile(path, contents);
  }
}

async function removeGeneratedPage(path) {
  try {
    const contents = await readFile(path, "utf8");
    if (!contents.includes(generatedPageMarker)) {
      throw new Error("Refusing to remove incantations.html because it was not generated by this script.");
    }
    await rm(path);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
}

async function updatePersonStructuredData(source, config, visible) {
  const pattern =
    /<script type="application\/ld\+json" id="person-jsonld">\s*([\s\S]*?)\s*<\/script>/;
  const match = source.match(pattern);
  if (!match) throw new Error("Could not find Person structured data.");
  const data = JSON.parse(match[1]);
  // The block is a ProfilePage wrapping the Person in mainEntity; resolve the
  // Person either way so the award update keeps working.
  const person = data.mainEntity ?? data;
  if (visible) {
    person.award = config.award;
  } else {
    delete person.award;
  }
  const replacement = `<script type="application/ld+json" id="person-jsonld">\n${JSON.stringify(data, null, 2)}\n</script>`;
  return source.replace(pattern, replacement);
}

function updateMetaContent(source, id, content) {
  const pattern = new RegExp(
    `(<meta\\s+[^>]*id="${id}"[^>]*content=")[^"]*("[^>]*>)`,
  );
  if (!pattern.test(source)) {
    throw new Error(`Could not find metadata field ${id}.`);
  }
  return source.replace(pattern, `$1${escapeHtml(content)}$2`);
}

async function copyProductionSnapshot(dedicatedPageEnabled) {
  const output = join(root, "_site");
  const publicPaths = [
    "404.html",
    "CNAME",
    "apple-touch-icon.png",
    "author-photo.jpg",
    "favicon-32.png",
    "favicon.ico",
    "index.html",
    "og-image.jpg",
    "publications.html",
    "publications.js",
    "research.html",
    "styles.css",
    "submittable-filter",
  ];
  if (dedicatedPageEnabled) publicPaths.push("incantations.html");

  await rm(output, { recursive: true, force: true });
  await mkdir(output, { recursive: true });
  for (const relativePath of publicPaths) {
    const source = join(root, relativePath);
    await access(source);
    const sourceStat = await stat(source);
    await cp(source, join(output, relativePath), {
      recursive: sourceStat.isDirectory(),
    });
  }
}

